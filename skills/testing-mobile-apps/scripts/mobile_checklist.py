PLAT_NAME = {"android": "Android", "ios": "iOS"}


def load_catalogue() -> dict:
    return json.loads((ASSETS / "mobile-checks.json").read_text(encoding="utf-8"))


def next_id(tests_path: str | None, start: int | None) -> int:
    if start:
        return start
    if tests_path and Path(tests_path).exists():
        data = json.loads(Path(tests_path).read_text(encoding="utf-8-sig"))
        ids = [int(m.group(1)) for t in (data.get("test_cases", []) if isinstance(data, dict) else data)
               if (m := re.match(r"TC-(\d+)", t.get("id", "")))]
        return (max(ids) + 1) if ids else 1
    return 1


def select_checks(cat: dict, platforms: list[str], caps: set[str]) -> list[dict]:
    out = []
    for c in cat["checks"]:
        if c["platform"] != "both" and c["platform"] not in platforms:
            continue
        if "core" in c["caps"] or caps & set(c["caps"]):
            out.append(c)
    return out


def via_text(check: dict, platforms: list[str], lang: str) -> str:
    via = check.get("via_tr" if lang == "tr" else "via") or check.get("via", {})
    plats = [p for p in platforms if p in via and (check["platform"] in ("both", p))]
    if len(plats) == 1:
        return via[plats[0]]
    return "; ".join(f"{PLAT_NAME[p]}: {via[p]}" for p in plats)


def render_checks(cat: dict, checks: list[dict], platforms: list[str], caps: set[str], req: str,
                  lang: str, first: int) -> tuple[list[str], int]:
    t = T[lang]
    lines = [t["head"].format(plat="+".join(platforms), caps=", ".join(["core"] + sorted(caps))), t["head2"]]
    n = first
    for c in checks:
        loc = c[lang]
        tid = f"TC-{n:03d}"
        n += 1
        plat_tags = [p for p in platforms if c["platform"] in ("both", p)]
        cap_tag = "core" if "core" in c["caps"] else next(x for x in c["caps"] if x in caps)
        tags = []
        for tag in ["mobile", *plat_tags, cap_tag, *c.get("tags", [])]:
            if tag not in tags:
                tags.append(tag)
        auto = cat["auto"][c["auto"]]
        lines += ["", f"## {tid} | {loc['title']}",
                  f"req: {req} | pri: {c['pri']} | pol: {c['pol']} | tech: {c['tech']} | cat: {c['cat']}"]
        for p in loc.get("pre", []):
            lines.append(f"pre: {p}")
        via = via_text(c, platforms, lang)
        for i, (act, exp) in enumerate(loc["steps"], 1):
            lines.append(f"{i}. {act.replace('{via}', via)} => {exp.replace('{via}', via)}")
        lines.append(f"tags: {', '.join(tags)} | auto: {'yes' if auto['candidate'] else 'no'}, {auto[lang]} | status: draft")
    questions = []
    for key in ["core", *sorted(caps)]:
        questions += cat.get("questions", {}).get(key, {}).get(lang, [])
    if questions:
        lines.append("")
        lines += [f"# QUESTION: {q}" for q in dict.fromkeys(questions)]
    return lines, n - first


# ---------------------------------------------------------------- device matrix

def version_key(v) -> tuple[int, ...]:
    nums = re.findall(r"\d+", str(v))
    return tuple(int(x) for x in nums) if nums else ()


def validate_devices(raw) -> tuple[list[dict], list[str]]:
    rows = raw.get("devices") if isinstance(raw, dict) else raw
    errors: list[str] = []
    if not isinstance(rows, list) or not rows:
        return [], ["devices file must be a non-empty list, or an object with a non-empty 'devices' list"]
    devices = []
    for i, d in enumerate(rows, 1):
        where = f"device #{i} ({d.get('name', '?') if isinstance(d, dict) else '?'})"
        if not isinstance(d, dict):
            errors.append(f"{where}: not an object")
            continue
        missing = [k for k in ("name", "os", "version", "share") if d.get(k) in (None, "")]
        if missing:
            errors.append(f"{where}: missing {', '.join(missing)}")
            continue
        os_ = str(d["os"]).strip().lower()
        if os_ not in PLATFORMS:
            errors.append(f"{where}: os must be android or ios, got '{d['os']}'")
            continue
        share = d["share"]
        if isinstance(share, bool) or not isinstance(share, (int, float)) or not 0 <= share <= 100:
            errors.append(f"{where}: share must be a number between 0 and 100")
            continue
        ff = str(d.get("form_factor", d.get("formFactor", "phone"))).strip().lower()
        if ff not in FORM_FACTORS:
            errors.append(f"{where}: form_factor must be one of {', '.join(FORM_FACTORS)}")
            continue
        if not version_key(d["version"]):
            errors.append(f"{where}: version '{d['version']}' has no number")
            continue
        width = d.get("width_dp")
        if width is not None and (isinstance(width, bool) or not isinstance(width, (int, float)) or width <= 0):
            errors.append(f"{where}: width_dp must be a positive number")
            continue
        devices.append({"name": str(d["name"]), "os": os_, "version": str(d["version"]), "share": float(share),
                        "form_factor": ff, "width_dp": width})
    for p in PLATFORMS:
        total = sum(d["share"] for d in devices if d["os"] == p)
        if total > 100.5:
            errors.append(f"{p}: shares add up to {total:.1f}% (> 100); 'share' is the percentage of this platform's users")
    return devices, errors


def select_devices(devs: list[dict], target: float) -> list[tuple[dict, list[str]]]:
    """Deterministic greedy selection: mandatory edges first, then descending share until the target."""
    chosen: dict[str, list[str]] = {}
    order: list[dict] = []

    def take(cands: list[dict], reason: str):
        if not cands:
            return
        best = sorted(cands, key=lambda d: (d["name"] not in chosen, -d["share"], d["name"]))[0]
        if best["name"] not in chosen:
            chosen[best["name"]] = []
            order.append(best)
        chosen[best["name"]].append(reason)

    vmin = min(version_key(d["version"]) for d in devs)
    vmax = max(version_key(d["version"]) for d in devs)
    take([d for d in devs if version_key(d["version"]) == vmin], "oldest")
    take([d for d in devs if version_key(d["version"]) == vmax], "newest")
    widths = [d for d in devs if d["width_dp"] and d["form_factor"] == "phone"] or [d for d in devs if d["width_dp"]]
    if widths:
        wmin = min(d["width_dp"] for d in widths)
        take([d for d in widths if d["width_dp"] == wmin], "smallest")
    take([d for d in devs if d["form_factor"] == "tablet"], "tablet")
    take([d for d in devs if d["form_factor"] == "foldable"], "foldable")
    covered = sum(d["share"] for d in order)
    for d in sorted(devs, key=lambda d: (-d["share"], d["name"])):
        if covered >= target - 1e-9:
            break
        if d["name"] in chosen:
            continue
        chosen[d["name"]] = ["share"]
        order.append(d)
        covered += d["share"]
    return [(d, chosen[d["name"]]) for d in order]


def fmt(x: float) -> str:
    return f"{x:.1f}"


def build_matrix(devices: list[dict], platforms: list[str], target: float, lang: str, src: str) -> tuple[str, list[str]]:
    t = T[lang]
    lines = [t["m_title"], "", t["m_src"].format(src=src), "", t["m_algo"].format(target=fmt(target))]
    warnings = []
    for p in platforms:
        devs = [d for d in devices if d["os"] == p]
        if not devs:
            continue
        sel = select_devices(devs, target)
        total = sum(d["share"] for d in devs)
        lines += ["", f"## {PLAT_NAME[p]}", "", t["m_cols"], "|---|---|---|---|---|---|---|---|"]
        cum = 0.0
        for i, (d, reasons) in enumerate(sel, 1):
            cum += d["share"]
            why = ", ".join(t["why"][r] for r in reasons)
            width = fmt(d["width_dp"]).removesuffix(".0") if d["width_dp"] else "-"
            lines.append(f"| {i} | {d['name']} | {PLAT_NAME[p]} {d['version']} | {d['form_factor']} | {width} | "
                         f"{fmt(d['share'])} | {fmt(cum)} | {why} |")
        lines += ["", t["m_sum"].format(n=len(sel), cov=fmt(cum), plat=PLAT_NAME[p], target=fmt(target), total=fmt(total))]
        if cum < target - 1e-9:
            w = t["m_warn"].format(plat=PLAT_NAME[p], total=fmt(total))
            warnings.append(w)
            lines += ["", f"> {w}"]
        names = {d["name"] for d, _ in sel}
        rest = sorted((d for d in devs if d["name"] not in names), key=lambda d: (-d["share"], d["name"]))
        lines += ["", t["m_rest"] + " " + ("; ".join(f"{d['name']} ({PLAT_NAME[p]} {d['version']}, {fmt(d['share'])}%)"
                                                     for d in rest) or t["m_none"])]
        by_ver: dict[str, float] = {}
        major = {}
        for d in devs:
            key = str(version_key(d["version"])[0])
            by_ver[key] = by_ver.get(key, 0.0) + d["share"]
            major.setdefault(key, False)
            if d["name"] in names:
                major[key] = True
        lines += ["", t["m_os"], "|---|---|---|"]
        for key in sorted(by_ver, key=lambda k: int(k), reverse=True):
            lines.append(f"| {PLAT_NAME[p]} {key} | {fmt(by_ver[key])} | {t['yes'] if major[key] else t['no']} |")
    lines += [""] + t["m_use"]
    return "\n".join(lines) + "\n", warnings


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--platform", choices=["ios", "android", "both"], default="both")
    ap.add_argument("--capabilities", default="", help="comma-separated capabilities (see --list-capabilities), or 'all'; core checks are always included")
    ap.add_argument("--list-capabilities", action="store_true")
    ap.add_argument("--req", default="", help="requirement ID(s) the generated tests trace to (required with --out)")
    ap.add_argument("--tests", help="existing test-cases.json to continue TC numbering")
    ap.add_argument("--start", type=int, help="first TC number (overrides --tests)")
    ap.add_argument("--lang", choices=["tr", "en"], default="en")
    ap.add_argument("--out", help="compact test cases (.src.md)")
    ap.add_argument("--devices", help="devices.json with per-platform user share (see assets/devices-example.json)")
    ap.add_argument("--matrix-out", dest="matrix_out", help="device coverage matrix (.md)")
    ap.add_argument("--target-share", dest="target_share", type=float, default=80.0, help="cumulative share per platform to reach (default 80)")
    sys.stdout.reconfigure(encoding="utf-8")
    a = ap.parse_args()
    cat = load_catalogue()
    if a.list_capabilities:
        for k, v in cat["capabilities"].items():
            print(f"{k:12s} {v[a.lang]}")
        return 0
    if not a.out and not a.matrix_out:
        print("error: nothing to do: give --out (test cases) and/or --devices with --matrix-out", file=sys.stderr)
        return 2
    if bool(a.devices) != bool(a.matrix_out):
        print("error: --devices and --matrix-out go together", file=sys.stderr)
        return 2
    if not 0 < a.target_share <= 100:
        print("error: --target-share must be in (0, 100]", file=sys.stderr)
        return 2
    platforms = list(PLATFORMS) if a.platform == "both" else [a.platform]
    raw_caps = {c.strip().lower() for c in a.capabilities.split(",") if c.strip()}
    caps = set(cat["capabilities"]) if "all" in raw_caps else raw_caps
    unknown = caps - set(cat["capabilities"])
    if unknown:
        print(f"error: unknown capabilities {sorted(unknown)}; use --list-capabilities", file=sys.stderr)
        return 2
    if a.out:
        if not a.req:
            print("error: --req is required with --out so the generated tests are traceable", file=sys.stderr)
            return 2
        checks = select_checks(cat, platforms, caps)
        lines, count = render_checks(cat, checks, platforms, caps, a.req, a.lang, next_id(a.tests, a.start))
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {a.out}: {count} test cases ({'+'.join(platforms)}; core + {', '.join(sorted(caps)) or 'no capabilities'})")
    if a.matrix_out:
        try:
            raw = json.loads(Path(a.devices).read_text(encoding="utf-8-sig"))
        except (OSError, ValueError) as e:
            print(f"error: cannot read {a.devices}: {e}", file=sys.stderr)
            return 2
        devices, errors = validate_devices(raw)
        if errors:
            for e in errors:
                print(f"error: {e}", file=sys.stderr)
            return 1
        md, warnings = build_matrix(devices, platforms, a.target_share, a.lang, Path(a.devices).name)
        Path(a.matrix_out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.matrix_out).write_text(md, encoding="utf-8", newline="\n")
        print(f"wrote {a.matrix_out}: device matrix for {'+'.join(platforms)} (target {fmt(a.target_share)}%)")
        for w in warnings:
            print(f"warning: {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
