#!/usr/bin/env python3
"""Draft mobile-specific test cases (QA Suite compact format) and a device coverage matrix.

Test cases (--out): an always-on core set for every iOS/Android app (install, upgrade with data
migration, reinstall, cold start, background/foreground, process death, low memory, rotation,
multi-window, interruptions, offline, connection loss mid-transaction, slow network, captive
portal, TLS, font scale, screen reader, touch targets/contrast, low storage, dark mode, Turkish
locale, jank, store privacy disclosures) plus sets for the capabilities you name. Platform-specific
variants are emitted per platform (e.g. iOS "Allow Once"/ATT vs Android "Only this time"/background
location). Each case has category, priority, technique (checklist / error guessing), tags
(mobile, android/ios, capability, masvs-*/wcag-*), steps with expected results, and an automation
hint. Review, adapt to the real app, then append to qa/test-cases.src.md and run qa_compact.py.

Device matrix (--devices + --matrix-out): picks, per platform, the mandatory edge devices
(oldest OS version, newest OS version, smallest screen, the top tablet and the top foldable if
listed), then adds the remaining devices in descending share order (ties by name) until the
cumulative share reaches --target-share. "share" is the percentage of THAT platform's active
users (from your analytics). Shares are disjoint, so once the edges are fixed this greedy order
reaches the target with the fewest devices. Deterministic: same input, same output.

devices.json: a list (or {"devices": [...]}) of objects with
  name, os ("android" | "ios"), version ("14", "17.5"), share (number), form_factor
  ("phone" | "tablet" | "foldable"), optional width_dp (logical width in dp/pt, for "smallest screen").

Usage:
  python mobile_checklist.py --platform both --capabilities push,payments,deeplinks,auth \\
      --req REQ-030 --tests qa/test-cases.json --lang tr --out qa/design/mobile.src.md
  python mobile_checklist.py --platform android --devices devices.json --target-share 80 \\
      --matrix-out qa/design/device-matrix.md
  python mobile_checklist.py --list-capabilities
Exit codes: 0 ok, 1 invalid devices file content, 2 usage error or unreadable input.
"""
